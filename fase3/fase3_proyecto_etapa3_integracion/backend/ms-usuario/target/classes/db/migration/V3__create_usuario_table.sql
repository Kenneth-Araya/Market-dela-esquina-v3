CREATE TABLE IF NOT EXISTS bd_usuarios.usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_usuario VARCHAR(9) NOT NULL UNIQUE,
    nombre_usuario VARCHAR(50) NOT NULL,
    apellidos_usuario VARCHAR(100) NOT NULL,
    correo_usuario VARCHAR(100) NOT NULL UNIQUE,
    fecha_nacimiento_usuario DATE,
    tipo_usuario VARCHAR(20) NOT NULL,
    region_usuario VARCHAR(100) NOT NULL,
    comuna_usuario VARCHAR(100) NOT NULL,
    direccion_usuario VARCHAR(300) NOT NULL,
    contrasena_usuario VARCHAR(100) NOT NULL,
    estado_usuario VARCHAR(20) NOT NULL,
    fecha_registro_usuario TIMESTAMP NOT NULL,
    CONSTRAINT ck_usuario_tipo
        CHECK (tipo_usuario IN ('ADMINISTRADOR', 'CLIENTE', 'VENDEDOR')),
    CONSTRAINT ck_usuario_estado
        CHECK (estado_usuario IN ('ACTIVO', 'INACTIVO'))
);