CREATE TABLE IF NOT EXISTS bd_catalogo.producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto VARCHAR(150) NOT NULL,
    descripcion_producto VARCHAR(1000),
    precio_producto INTEGER NOT NULL,
    peso_producto VARCHAR(50),
    imagen_producto VARCHAR(255),
    rating_producto DOUBLE PRECISION,
    activo_producto BOOLEAN NOT NULL DEFAULT TRUE,
    id_categoria BIGINT,
    CONSTRAINT fk_producto_categoria
        FOREIGN KEY (id_categoria) REFERENCES bd_catalogo.categoria (id),
    CONSTRAINT ck_producto_precio
        CHECK (precio_producto >= 0)
);