CREATE TABLE IF NOT EXISTS bd_catalogo.movimiento_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL,
    tipo_movimiento VARCHAR(20) NOT NULL,
    cantidad_movimiento INTEGER NOT NULL,
    motivo_movimiento VARCHAR(200),
    id_venta BIGINT,
    fecha_movimiento TIMESTAMP NOT NULL,
    CONSTRAINT fk_movimiento_inventario_producto
        FOREIGN KEY (id_producto) REFERENCES bd_catalogo.producto (id),
    CONSTRAINT ck_movimiento_inventario_tipo
        CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA', 'AJUSTE'))
);