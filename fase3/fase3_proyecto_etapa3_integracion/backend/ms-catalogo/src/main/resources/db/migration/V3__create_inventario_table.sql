CREATE TABLE IF NOT EXISTS bd_catalogo.inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL UNIQUE,
    stock_actual INTEGER NOT NULL DEFAULT 0,
    stock_minimo INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_inventario_producto
        FOREIGN KEY (id_producto) REFERENCES bd_catalogo.producto (id),
    CONSTRAINT ck_inventario_stock_actual
        CHECK (stock_actual >= 0),
    CONSTRAINT ck_inventario_stock_minimo
        CHECK (stock_minimo >= 0)
);