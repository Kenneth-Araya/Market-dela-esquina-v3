CREATE TABLE IF NOT EXISTS bd_administracion.mensaje_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_contacto VARCHAR(100) NOT NULL,
    correo_contacto VARCHAR(100) NOT NULL,
    contenido_contacto VARCHAR(2000) NOT NULL,
    fecha_envio_contacto TIMESTAMP NOT NULL,
    estado_contacto VARCHAR(20) NOT NULL,
    CONSTRAINT ck_mensaje_contacto_estado
        CHECK (estado_contacto IN ('NUEVO', 'LEIDO', 'RESPONDIDO'))
);