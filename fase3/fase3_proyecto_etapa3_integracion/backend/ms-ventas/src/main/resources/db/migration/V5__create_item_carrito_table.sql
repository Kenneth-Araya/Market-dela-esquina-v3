CREATE TABLE IF NOT EXISTS bd_ventas.item_carrito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrito BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,
    cantidad_item INTEGER NOT NULL,
    CONSTRAINT fk_item_carrito_carrito
        FOREIGN KEY (id_carrito) REFERENCES bd_ventas.carrito (id),
    CONSTRAINT ck_item_carrito_cantidad
        CHECK (cantidad_item > 0)
);