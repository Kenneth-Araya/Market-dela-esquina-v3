CREATE TABLE IF NOT EXISTS bd_ventas.detalle_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    precio_unitario_detalle INTEGER NOT NULL,
    cantidad_detalle INTEGER NOT NULL,
    subtotal_detalle INTEGER NOT NULL,
    CONSTRAINT fk_detalle_venta_venta
        FOREIGN KEY (id_venta) REFERENCES bd_ventas.venta (id),
    CONSTRAINT ck_detalle_venta_cantidad
        CHECK (cantidad_detalle > 0)
);