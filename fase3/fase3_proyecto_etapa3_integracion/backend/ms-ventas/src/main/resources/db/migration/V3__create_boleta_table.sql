CREATE TABLE IF NOT EXISTS bd_ventas.boleta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_boleta VARCHAR(20) NOT NULL UNIQUE,
    id_venta BIGINT NOT NULL UNIQUE,
    fecha_emision_boleta TIMESTAMP NOT NULL,
    total_boleta INTEGER NOT NULL,
    CONSTRAINT fk_boleta_venta
        FOREIGN KEY (id_venta) REFERENCES bd_ventas.venta (id)
);