CREATE SCHEMA IF NOT EXISTS bd_ventas;

CREATE TABLE IF NOT EXISTS bd_ventas.venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    fecha_venta TIMESTAMP NOT NULL,
    subtotal_venta INTEGER NOT NULL,
    total_venta INTEGER NOT NULL,
    estado_venta VARCHAR(20) NOT NULL,
    CONSTRAINT ck_venta_estado
        CHECK (estado_venta IN ('PENDIENTE', 'PAGADA', 'ANULADA'))
);